/* ============================================================
   AI Study Assistant — script.js
   Vanilla JS only. Each study feature is generated by the
   Express backend in /backend, which calls OpenRouter and
   returns JSON in the same shape the render* functions below
   expect. See API_BASE_URL if the backend runs somewhere
   other than http://localhost:5000.
   ============================================================ */
(function () {
  'use strict';

  /* ---------------- Helpers ---------------- */
  function $(sel, scope) { return (scope || document).querySelector(sel); }
  function $all(sel, scope) { return Array.prototype.slice.call((scope || document).querySelectorAll(sel)); }
  function escapeHtml(str) {
    const div = document.createElement('div');
    div.textContent = str == null ? '' : String(str);
    return div.innerHTML;
  }
  function bytesToSize(bytes) {
    if (bytes === 0) return '0 B';
    const sizes = ['B', 'KB', 'MB', 'GB'];
    const i = Math.floor(Math.log(bytes) / Math.log(1024));
    return (bytes / Math.pow(1024, i)).toFixed(i === 0 ? 0 : 1) + ' ' + sizes[i];
  }
  function extOf(name) {
    const parts = name.split('.');
    return parts.length > 1 ? parts.pop().toLowerCase() : '';
  }

  /* ---------------- Theme ---------------- */
  const THEME_KEY = 'sa-theme';
  const root = document.documentElement;
  function initTheme() {
    let saved = null;
    try { saved = localStorage.getItem(THEME_KEY); } catch (e) { /* storage unavailable */ }
    if (saved === 'dark' || saved === 'light') {
      root.setAttribute('data-theme', saved);
    } else if (window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches) {
      root.setAttribute('data-theme', 'dark');
    }
  }
  function toggleTheme() {
    const next = root.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
    root.setAttribute('data-theme', next);
    try { localStorage.setItem(THEME_KEY, next); } catch (e) { /* storage unavailable */ }
  }
  initTheme();
  $('#theme-toggle').addEventListener('click', toggleTheme);

  /* ---------------- Toasts ---------------- */
  const toastStack = $('#toast-stack');
  function showToast(message, type) {
    const el = document.createElement('div');
    el.className = 'toast' + (type === 'error' ? ' is-error' : '');
    el.innerHTML =
      '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">' +
      (type === 'error' ? '<circle cx="12" cy="12" r="9"/><path d="M12 7.5v5M12 16h.01"/>' : '<path d="M5 13l4 4L19 7"/>') +
      '</svg><span></span>';
    el.querySelector('span').textContent = message;
    toastStack.appendChild(el);
    setTimeout(function () {
      el.classList.add('is-leaving');
      setTimeout(function () { el.remove(); }, 220);
    }, 2600);
  }

  /* ---------------- View switching ---------------- */
  function showView(id) {
    $all('.view').forEach(function (v) { v.classList.toggle('is-active', v.id === 'view-' + id); });
    $all('.main-nav .nav-link').forEach(function (link) {
      const nav = link.dataset.nav;
      const isCurrent = nav === 'landing' ? id === 'landing' : id !== 'landing';
      link.classList.toggle('is-current', isCurrent);
    });
    window.scrollTo({ top: 0, behavior: 'smooth' });
  }
  $all('[data-nav]').forEach(function (el) {
    el.addEventListener('click', function () { showView(el.dataset.nav); });
  });

  /* ---------------- Upload ---------------- */
  const ALLOWED_EXT = ['pdf', 'ppt', 'pptx', 'doc', 'docx', 'txt', 'jpg', 'jpeg', 'png'];
  const MAX_SIZE = 25 * 1024 * 1024;

  const dropzone = $('#dropzone');
  const fileInput = $('#file-input');
  const fileCard = $('#file-card');
  const fileCardName = $('#file-card-name');
  const fileCardMeta = $('#file-card-meta');
  const progressBar = $('#file-card-progress-bar');
  const analyzeBtn = $('#analyze-btn');
  let currentFile = null;
  let progressTimer = null;

  ['dragenter', 'dragover'].forEach(function (evt) {
    dropzone.addEventListener(evt, function (e) {
      e.preventDefault();
      dropzone.classList.add('is-dragover');
    });
  });
  ['dragleave', 'drop'].forEach(function (evt) {
    dropzone.addEventListener(evt, function (e) {
      e.preventDefault();
      dropzone.classList.remove('is-dragover');
    });
  });
  dropzone.addEventListener('drop', function (e) {
    const files = e.dataTransfer && e.dataTransfer.files;
    if (files && files[0]) handleFile(files[0]);
  });
  fileInput.addEventListener('change', function (e) {
    if (e.target.files && e.target.files[0]) handleFile(e.target.files[0]);
  });

  function handleFile(file) {
    const ext = extOf(file.name);
    if (ALLOWED_EXT.indexOf(ext) === -1) {
      showToast('Unsupported file type. Please upload PDF, PPT, PPTX, DOC, DOCX, TXT, JPG or PNG.', 'error');
      return;
    }
    if (file.size > MAX_SIZE) {
      showToast('That file is too large. Maximum size is 25 MB.', 'error');
      return;
    }
    currentFile = file;
    dropzone.style.display = 'none';
    fileCard.style.display = 'flex';
    fileCardName.textContent = file.name;
    fileCardMeta.textContent = ext.toUpperCase() + ' · ' + bytesToSize(file.size);
    analyzeBtn.disabled = true;
    progressBar.style.width = '0%';
    if (progressTimer) clearInterval(progressTimer);
    let pct = 0;
    progressTimer = setInterval(function () {
      pct += Math.random() * 22 + 14;
      if (pct >= 100) {
        pct = 100;
        clearInterval(progressTimer);
        analyzeBtn.disabled = false;
      }
      progressBar.style.width = pct + '%';
    }, 140);
  }

  $('#file-card-remove').addEventListener('click', function () {
    currentFile = null;
    fileInput.value = '';
    if (progressTimer) clearInterval(progressTimer);
    fileCard.style.display = 'none';
    dropzone.style.display = '';
    analyzeBtn.disabled = true;
  });

  analyzeBtn.addEventListener('click', function () {
    showView('processing');
    runProcessingSequence();
  });

  function runProcessingSequence() {
    const items = $all('#processing-checklist li');
    items.forEach(function (li) { li.classList.remove('is-shown', 'is-done'); });
    let i = 0;
    function next() {
      if (i < items.length) {
        items[i].classList.add('is-shown');
        setTimeout(function () {
          items[i].classList.add('is-done');
          i++;
          next();
        }, 600);
      } else {
        setTimeout(function () { showView('ready'); }, 450);
      }
    }
    next();
  }

  $('#ready-continue-btn').addEventListener('click', function () { showView('options'); });

  /* ---------------- Backend connection ----------------
     Change this if the backend isn't running on localhost:5000
     (see backend/.env.example for the server-side PORT). */
  const API_BASE_URL = 'http://localhost:5000';

  // Holds the last AI response for the currently open feature, in the
  // same shape the render* functions below expect:
  // { topic, summary|questions|mcqs|quiz|flashcards|keypoints }
  let currentData = null;

  const FEATURE_LABELS = {
    summary: 'Summary',
    questions: 'Important Questions',
    mcq: 'MCQs',
    quiz: 'Quiz',
    flashcards: 'Flashcards',
    keypoints: 'Key Points'
  };

  /* ---------------- Study options → feature open ---------------- */
  $all('.option-card').forEach(function (card) {
    card.addEventListener('click', function () { openFeature(card.dataset.feature); });
  });

  function openFeature(feature) {
    if (!currentFile) {
      showToast('Please upload a file first.', 'error');
      showView('upload');
      return;
    }

    $('#generating-label').textContent = 'AI is generating your ' + FEATURE_LABELS[feature] + '\u2026';
    showView('generating');

    const formData = new FormData();
    formData.append('file', currentFile);
    formData.append('type', feature);

    fetch(API_BASE_URL + '/api/study/process', { method: 'POST', body: formData })
      .then(function (res) {
        return res.json().catch(function () { return {}; }).then(function (body) {
          if (!res.ok || !body || !body.success) {
            throw new Error((body && body.error) || 'Something went wrong. Please try again.');
          }
          return body;
        });
      })
      .then(function (body) {
        currentData = body.data;
        renderFeature(feature);
        showView('result-' + feature);
        if (body.warning) showToast(body.warning);
      })
      .catch(function (err) {
        showToast(err.message || 'Could not reach the AI Study Assistant backend.', 'error');
        showView('options');
      });
  }

  function renderFeature(feature) {
    const renderers = {
      summary: renderSummary,
      questions: renderQuestions,
      mcq: renderMCQs,
      quiz: renderQuiz,
      flashcards: renderFlashcards,
      keypoints: renderKeyPoints
    };
    renderers[feature]();
  }

  /* ---------------- Summary ---------------- */
  function renderSummary() {
    const s = currentData.summary;
    $('#summary-title').textContent = 'Summary — ' + currentData.topic;
    $('#summary-content').innerHTML =
      '<div class="summary-block"><h3>Overview</h3><p>' + escapeHtml(s.overview) + '</p></div>' +
      '<div class="summary-block"><h3>Main Topics</h3><div class="topic-tags">' +
      s.mainTopics.map(function (t) { return '<span class="topic-tag">' + escapeHtml(t) + '</span>'; }).join('') +
      '</div></div>' +
      '<div class="summary-block"><h3>Detailed Summary</h3>' +
      s.detailed.map(function (p) { return '<p style="margin-bottom:14px">' + escapeHtml(p) + '</p>'; }).join('') +
      '</div>' +
      '<div class="summary-block"><h3>Key Takeaways</h3><ul class="takeaway-list">' +
      s.takeaways.map(function (t) { return '<li>' + escapeHtml(t) + '</li>'; }).join('') +
      '</ul></div>';
  }

  /* ---------------- Important Questions ---------------- */
  function renderQuestions() {
    const list = $('#questions-list');
    list.innerHTML = currentData.questions.map(function (item, i) {
      return '<li class="q-item">' +
        '<div class="q-item-head"><span class="q-num">' + String(i + 1).padStart(2, '0') + '</span>' +
        '<span class="q-topic">' + escapeHtml(item.topic) + '</span>' +
        '<span class="q-diff ' + item.difficulty + '">' + item.difficulty + '</span></div>' +
        '<p class="q-text">' + escapeHtml(item.q) + '</p>' +
        '<button class="btn btn-ghost btn-sm q-reveal" data-reveal>Show answer</button>' +
        '<p class="q-answer">' + escapeHtml(item.a) + '</p></li>';
    }).join('');
    $all('[data-reveal]', list).forEach(function (btn) {
      btn.addEventListener('click', function () { btn.closest('.q-item').classList.add('is-revealed'); });
    });
  }

  /* ---------------- MCQs ---------------- */
  function renderMCQs() {
    const wrap = $('#mcq-list');
    const letters = ['A', 'B', 'C', 'D'];
    wrap.innerHTML = currentData.mcqs.map(function (item, i) {
      const options = item.options.map(function (opt, oi) {
        return '<div class="mcq-option' + (oi === item.correct ? ' correct' : '') + '">' +
          '<span class="letter">' + letters[oi] + '</span><span>' + escapeHtml(opt) + '</span></div>';
      }).join('');
      return '<div class="mcq-item"><p class="mcq-q">' + (i + 1) + '. ' + escapeHtml(item.q) + '</p>' +
        '<div class="mcq-options">' + options + '</div>' +
        '<button class="btn btn-ghost btn-sm mcq-reveal" data-reveal>Reveal answer</button>' +
        '<p class="mcq-explain">' + escapeHtml(item.explain) + '</p></div>';
    }).join('');
    $all('[data-reveal]', wrap).forEach(function (btn) {
      btn.addEventListener('click', function () { btn.closest('.mcq-item').classList.add('is-revealed'); });
    });
  }

  /* ---------------- Quiz ---------------- */
  let quizState = { index: 0, score: 0, answered: false };

  function renderQuiz() {
    quizState = { index: 0, score: 0, answered: false };
    renderQuizQuestion();
  }

  function renderQuizQuestion() {
    const container = $('#quiz-container');
    const total = currentData.quiz.length;
    const item = currentData.quiz[quizState.index];
    const letters = ['A', 'B', 'C', 'D'];
    container.innerHTML =
      '<div class="quiz-panel">' +
      '<div class="quiz-progress"><div class="quiz-progress-track"><div class="quiz-progress-bar" style="width:' + ((quizState.index / total) * 100) + '%"></div></div>' +
      '<span class="quiz-progress-label">Question ' + (quizState.index + 1) + ' of ' + total + '</span></div>' +
      '<p class="quiz-question">' + escapeHtml(item.q) + '</p>' +
      '<div class="quiz-options">' +
      item.options.map(function (opt, oi) {
        return '<button class="quiz-option" data-oi="' + oi + '"><span class="letter">' + letters[oi] + '</span><span>' + escapeHtml(opt) + '</span></button>';
      }).join('') +
      '</div><div class="quiz-footer"><button class="btn btn-primary" id="quiz-next-btn" style="display:none">Next Question</button></div></div>';

    $all('.quiz-option', container).forEach(function (btn) {
      btn.addEventListener('click', function () { selectQuizAnswer(parseInt(btn.dataset.oi, 10)); });
    });
  }

  function selectQuizAnswer(oi) {
    if (quizState.answered) return;
    quizState.answered = true;
    const item = currentData.quiz[quizState.index];
    $all('.quiz-option').forEach(function (btn, i) {
      btn.disabled = true;
      if (i === item.correct) btn.classList.add('correct');
      else if (i === oi) btn.classList.add('incorrect');
    });
    if (oi === item.correct) quizState.score++;
    const isLast = quizState.index === currentData.quiz.length - 1;
    const nextBtn = $('#quiz-next-btn');
    nextBtn.style.display = 'inline-flex';
    nextBtn.textContent = isLast ? 'See Results' : 'Next Question';
    nextBtn.onclick = function () {
      quizState.index++;
      quizState.answered = false;
      if (quizState.index >= currentData.quiz.length) renderQuizResult();
      else renderQuizQuestion();
    };
  }

  function renderQuizResult() {
    const total = currentData.quiz.length;
    const pct = Math.round((quizState.score / total) * 100);
    const headline = pct >= 80 ? 'Excellent work!' : pct >= 50 ? 'Good effort!' : 'Keep practicing!';
    $('#quiz-container').innerHTML =
      '<div class="quiz-panel quiz-result">' +
      '<div class="quiz-score">' + quizState.score + '<span>/' + total + '</span></div>' +
      '<h2>' + headline + '</h2><p>You scored ' + pct + '% on this quiz.</p>' +
      '<div class="quiz-result-actions">' +
      '<button class="btn btn-primary" id="quiz-restart-btn">Restart Quiz</button>' +
      '<button class="btn btn-secondary" id="quiz-back-btn">Back to Study Options</button></div></div>';
    $('#quiz-restart-btn').addEventListener('click', renderQuiz);
    $('#quiz-back-btn').addEventListener('click', function () { showView('options'); });
  }

  /* ---------------- Flashcards ---------------- */
  let flashState = { index: 0 };

  function renderFlashcards() {
    flashState = { index: 0 };
    renderFlashcard();
  }

  function renderFlashcard() {
    const container = $('#flashcards-container');
    const total = currentData.flashcards.length;
    const item = currentData.flashcards[flashState.index];
    container.innerHTML =
      '<div class="flash-wrap"><p class="flash-count">Card ' + (flashState.index + 1) + ' of ' + total + '</p>' +
      '<div class="flashcard" id="flashcard" tabindex="0" role="button" aria-label="Flip flashcard"><div class="flashcard-inner">' +
      '<div class="flashcard-face flashcard-front"><span class="kicker">Question</span><p>' + escapeHtml(item.front) + '</p></div>' +
      '<div class="flashcard-face flashcard-back"><span class="kicker">Answer</span><p>' + escapeHtml(item.back) + '</p></div>' +
      '</div></div><p class="flash-hint">Tap the card to flip it</p>' +
      '<div class="flash-nav"><button class="btn btn-secondary btn-sm" id="flash-prev">Previous</button>' +
      '<div class="flash-dots">' + currentData.flashcards.map(function (_, i) {
        return '<span class="flash-dot' + (i === flashState.index ? ' is-current' : '') + '"></span>';
      }).join('') + '</div>' +
      '<button class="btn btn-secondary btn-sm" id="flash-next">Next</button></div></div>';

    const card = $('#flashcard');
    function flip() { card.classList.toggle('is-flipped'); }
    card.addEventListener('click', flip);
    card.addEventListener('keydown', function (e) { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); flip(); } });
    $('#flash-prev').addEventListener('click', function () {
      flashState.index = (flashState.index - 1 + total) % total;
      renderFlashcard();
    });
    $('#flash-next').addEventListener('click', function () {
      flashState.index = (flashState.index + 1) % total;
      renderFlashcard();
    });
  }

  /* ---------------- Key Points ---------------- */
  function renderKeyPoints() {
    $('#keypoints-list').innerHTML = currentData.keypoints.map(function (point, i) {
      return '<div class="keypoint"><span class="keypoint-mark">' + String(i + 1).padStart(2, '0') + '</span><p>' + escapeHtml(point) + '</p></div>';
    }).join('');
  }

  /* ---------------- Result controls: copy / download / print / regenerate / back ---------------- */
  function textForFeature(feature) {
    const t = currentData.topic;
    if (feature === 'summary') {
      const s = currentData.summary;
      return 'Summary — ' + t + '\n\nOverview:\n' + s.overview +
        '\n\nMain Topics:\n' + s.mainTopics.join(', ') +
        '\n\nDetailed Summary:\n' + s.detailed.join('\n\n') +
        '\n\nKey Takeaways:\n' + s.takeaways.map(function (x) { return '- ' + x; }).join('\n');
    }
    if (feature === 'questions') {
      return 'Important Questions — ' + t + '\n\n' + currentData.questions.map(function (q, i) {
        return (i + 1) + '. [' + q.topic + ' · ' + q.difficulty + '] ' + q.q + '\nAnswer: ' + q.a;
      }).join('\n\n');
    }
    if (feature === 'mcq') {
      return 'MCQs — ' + t + '\n\n' + currentData.mcqs.map(function (m, i) {
        const opts = m.options.map(function (o, oi) {
          return '   ' + String.fromCharCode(65 + oi) + '. ' + o + (oi === m.correct ? '  (correct)' : '');
        }).join('\n');
        return (i + 1) + '. ' + m.q + '\n' + opts + '\nExplanation: ' + m.explain;
      }).join('\n\n');
    }
    if (feature === 'quiz') {
      return 'Quiz — ' + t + '\n\n' + currentData.quiz.map(function (q, i) {
        const opts = q.options.map(function (o, oi) {
          return '   ' + String.fromCharCode(65 + oi) + '. ' + o + (oi === q.correct ? '  (correct)' : '');
        }).join('\n');
        return (i + 1) + '. ' + q.q + '\n' + opts;
      }).join('\n\n');
    }
    if (feature === 'flashcards') {
      return 'Flashcards — ' + t + '\n\n' + currentData.flashcards.map(function (c, i) {
        return (i + 1) + '. Q: ' + c.front + '\n   A: ' + c.back;
      }).join('\n\n');
    }
    if (feature === 'keypoints') {
      return 'Key Points — ' + t + '\n\n' + currentData.keypoints.map(function (p, i) { return (i + 1) + '. ' + p; }).join('\n');
    }
    return '';
  }

  function fallbackCopy(text) {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.style.position = 'fixed';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.select();
    try {
      document.execCommand('copy');
      showToast('Copied to clipboard');
    } catch (e) {
      showToast('Could not copy — please select and copy manually.', 'error');
    }
    document.body.removeChild(ta);
  }

  function copyFeature(feature) {
    const text = textForFeature(feature);
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(text).then(
        function () { showToast('Copied to clipboard'); },
        function () { fallbackCopy(text); }
      );
    } else {
      fallbackCopy(text);
    }
  }

  function downloadFeature(feature) {
    const text = textForFeature(feature);
    const blob = new Blob([text], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = feature + '-' + currentData.topic.toLowerCase().replace(/\s+/g, '-') + '.txt';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
    showToast('Download started');
  }

  function initResultControls() {
    $all('[data-feature-controls]').forEach(function (bar) {
      const feature = bar.dataset.featureControls;
      const tpl = $('#controls-template');
      bar.appendChild(tpl.content.cloneNode(true));
      bar.querySelector('[data-action="copy"]').addEventListener('click', function () { copyFeature(feature); });
      bar.querySelector('[data-action="download"]').addEventListener('click', function () { downloadFeature(feature); });
      bar.querySelector('[data-action="print"]').addEventListener('click', function () { window.print(); });
      bar.querySelector('[data-action="regenerate"]').addEventListener('click', function () { openFeature(feature); });
      bar.querySelector('[data-action="back"]').addEventListener('click', function () { showView('options'); });
    });
  }

  /* ---------------- Init ---------------- */
  initResultControls();
})();
